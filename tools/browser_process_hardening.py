"""Keep the browser-control key and slot command tokens out of same-uid ``/proc`` reads.

Managed browser mode puts ``HERMES_BROWSER_CONTROL_KEY`` in the gateway's
environment and a live slot command token (inside ``BU_CDP_URL``) in every
Browser Use harness process. Model-written code runs as the same uid, and
``/proc/<pid>/environ`` of a dumpable process is readable by that uid (Yama
``ptrace_scope=1`` blocks attach, not environ reads). ``prctl(PR_SET_DUMPABLE,
0)`` makes those files root-owned. It is Linux-only and a no-op elsewhere; it
also disables core dumps and same-uid debuggers (py-spy, gdb) for that process.

The dumpable flag resets on every ``execve``, so each process sets it itself:
the gateway when it imports the managed-control client, and every harness
process through a generated ``sitecustomize`` placed first on its
``PYTHONPATH``. This is hardening, not a boundary: root, and code that runs
before the call, still see the values.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path
from typing import Optional

logger = logging.getLogger(__name__)

PR_SET_DUMPABLE = 4

# Standalone: runs in the harness interpreter, which has no Hermes on sys.path.
SITECUSTOMIZE = """\
# Generated by Hermes (tools/browser_process_hardening.py): make this process
# undumpable so same-uid code cannot read its environment from /proc.
def _hermes_undumpable():
    import sys
    if not sys.platform.startswith("linux"):
        return
    try:
        import ctypes
        ctypes.CDLL(None, use_errno=True).prctl(4, 0, 0, 0, 0)
    except Exception:
        pass
_hermes_undumpable()
del _hermes_undumpable
"""


def _linux() -> bool:
    from hermes_platform.host.facts import os_family

    return os_family().startswith("linux")


def make_undumpable() -> bool:
    """``prctl(PR_SET_DUMPABLE, 0)`` on Linux; True when it took effect."""
    if not _linux():
        return False
    import ctypes

    try:
        return ctypes.CDLL(None, use_errno=True).prctl(PR_SET_DUMPABLE, 0, 0, 0, 0) == 0
    except (OSError, AttributeError) as exc:
        logger.debug("PR_SET_DUMPABLE unavailable: %s", exc)
        return False


def harness_site_dir() -> Optional[str]:
    """A directory holding the hardening ``sitecustomize.py``, written on demand; None on failure."""
    from hermes_constants import get_hermes_home

    try:
        site = Path(get_hermes_home()) / "cache" / "browser-use" / "hardening-site"
        target = site / "sitecustomize.py"
        if not target.is_file() or target.read_text(encoding="utf-8-sig") != SITECUSTOMIZE:
            site.mkdir(parents=True, exist_ok=True)
            tmp = target.with_name(f".sitecustomize.{os.getpid()}.tmp")
            tmp.write_text(SITECUSTOMIZE, encoding="utf-8")
            os.replace(tmp, target)
        return str(site)
    except OSError as exc:
        logger.debug("harness hardening site unavailable: %s", exc)
        return None


def harden_harness_env(env: dict) -> None:
    """Put the hardening ``sitecustomize`` first on the harness ``PYTHONPATH`` (Linux only)."""
    if not _linux():
        return
    site = harness_site_dir()
    if site:
        rest = env.get("PYTHONPATH", "")
        env["PYTHONPATH"] = site + (os.pathsep + rest if rest else "")
